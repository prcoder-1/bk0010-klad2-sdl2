/*
 * Интерпретатор КР1801ВМ1 (PDP-11-совместимый + sob/xor).
 *
 * Доступ к памяти идёт исключительно через bk_read_X и bk_write_X
 * (см. bk.h) — это и есть точка, где регистры периферии получают
 * семантику. Регистры ЦП живут в структуре `cpu_t`.
 *
 * PSW: биты слова состояния процессора по PDP-11:
 *   бит 0 — C (carry)
 *   бит 1 — V (overflow)
 *   бит 2 — Z (zero)
 *   бит 3 — N (negative)
 *   бит 4 — T (trap, пошаговый режим)
 *   биты 5..7 — приоритет прерываний (в БК-0010 не используются игрой)
 */

#ifndef KLAD2_PDP11_H
#define KLAD2_PDP11_H

#include <stdint.h>

enum PSW_BITS {
    PSW_C = 0x0001,
    PSW_V = 0x0002,
    PSW_Z = 0x0004,
    PSW_N = 0x0008,
    PSW_T = 0x0010
};

typedef struct {
    uint16_t r[8];   /* R0..R5, R6=SP, R7=PC */
    uint16_t psw;
    int      halted; /* 1 — выполнен HALT или невосстановимая ошибка */
} cpu_t;

/* Единственный экземпляр процессора — игры на одном ЦП. */
extern cpu_t cpu;

/* Сбросить регистры: PC = entry, SP = stack, PSW = 0, halted = 0. */
void pdp11_reset(uint16_t entry_pc, uint16_t stack_top);

/* Один шаг: fetch / decode / execute. Возвращает 0 в норме, -1 если
 * процессор остановлен (HALT, неизвестная инструкция, фатальная
 * ошибка). После -1 шагать дальше бессмысленно — нужен reset. */
int pdp11_step(void);

/* Сделать до `max_steps` шагов либо до halted, в зависимости от того,
 * что наступит раньше. Возвращает фактическое число выполненных шагов.
 * Используется в главном цикле между кадрами рендера. */
int pdp11_run_n(int max_steps);

/* Установить EMT-обработчик. Вызывается при инструкции EMT с номером
 * 0..255; обработчик может править cpu.r[]/bk_mem напрямую (как реальные
 * драйверы БК-ROM). */
typedef void (*emt_handler_fn)(unsigned emt_no);
void pdp11_set_emt_handler(emt_handler_fn fn);

/* Аналогично для TRAP (на БК-0010 встречается реже). */
void pdp11_set_trap_handler(emt_handler_fn fn);

/* Включение/выключение трассы. При включённой трассе перед каждой
 * инструкцией в stderr выводится строка с PC, опкодом и регистрами —
 * грубый дебаг для разведки в Фазах 5–6. */
void pdp11_set_trace(int on);

#endif /* KLAD2_PDP11_H */
