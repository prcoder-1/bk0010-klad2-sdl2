/*
 * Виртуальная БК-0010 для Linux/SDL2-порта КЛАД-2.
 *
 * Адресное пространство 64 КиБ моделируется массивом `bk_mem`. Чтение/
 * запись через `bk_read_*`/`bk_write_*` прозрачно ходят в RAM/видеоОЗУ,
 * а доступ к диапазону регистров `0o177600..0o177777` перехватывается и
 * перенаправляется в input.c/audio.c/video.c — как на реальной машине.
 *
 * Карта памяти, имена регистров и константы экрана — перенесены из
 * `/home/prcoder/БК0010-develop/digger-bk0010/memory.h` (порт Digger на БК):
 * там это уже отлажено для реального железа, а нам нужны ровно те же
 * идентификаторы, чтобы упростить чтение кросс-проектных параллелей.
 */

#ifndef KLAD2_BK_H
#define KLAD2_BK_H

#include <stdint.h>

#define BK_MEM_SIZE  0x10000u  /* 64 КиБ адресного пространства */

/* ----- Распределение адресного пространства БК-0010 ------------------- */
enum BK_MEMORY {
    MEM_SYSTEM  = 0000000, /* Системные переменные */
    MEM_STACK   = 0000300, /* Стек */
    MEM_USER    = 0001000, /* ОЗУ пользователя */
    MEM_VIDEO   = 0040000, /* ОЗУ экрана (16 КиБ) */
    MEM_EXTMEM  = 0070000, /* ОЗУ экрана в режиме расширенной памяти */
    MEM_ROM_MON = 0100000, /* ПЗУ монитора и драйверы */
    MEM_ROM_1   = 0120000, /* 1-съёмное ПЗУ "Бейсик" (Фокал) */
    MEM_ROM_2   = 0140000, /* 2-съёмное ПЗУ "Бейсик" */
    MEM_ROM_3   = 0160000, /* 3-съёмное ПЗУ "Бейсик" (Тесты МСТД) */
    MEM_REGS    = 0177600, /* Область системных регистров */
    MEM_END     = 0177777  /* Конец памяти */
};

/* ----- Векторы прерываний --------------------------------------------- */
enum BK_VECTORS {
    VEC_STOP          = 000004, /* "СТОП" / зависание канала */
    VEC_RES_CPU_INSTR = 000010, /* Зарезервированная инструкция */
    VEC_T_BIT         = 000014, /* По Т-разряду */
    VEC_IOT           = 000020, /* IOT */
    VEC_POWER_FAIL    = 000024, /* Авария питания */
    VEC_EMT           = 000030, /* EMT */
    VEC_TRAP          = 000034, /* TRAP */
    VEC_KEYBOARD      = 000060, /* Прерывание от клавиатуры */
    VEC_IRQ2          = 000100, /* Сигнал IRQ2 */
    VEC_KEY_LOW_REG   = 000274  /* Прерывание от клавиатуры (нижний регистр) */
};

/* ----- Системные ячейки памяти ---------------------------------------- */
enum BK_SYSTEM {
    /* Биты слова состояния дисплея (зеркало в RAM 0o40..0o57) */
    SYS_COLOR        = 0040, /* Цветной режим (32 символа в строке) */
    SYS_SCR_INVERSE  = 0041,
    SYS_EXT_MEMORY   = 0042,
    SYS_RUS          = 0043,
    SYS_UNDERLINE    = 0044,
    SYS_SYM_INVERSE  = 0045,
    SYS_IND_SU       = 0046,
    SYS_BLOCK_RED    = 0047,
    SYS_GRAPH        = 0050,
    SYS_ZAP          = 0051,
    SYS_STIR         = 0052,
    SYS_S_LINE_32    = 0053,
    SYS_S_LINE_UND   = 0054,
    SYS_S_LINE_INV   = 0055,
    SYS_CURSOR_OFF   = 0056,
    SYS_UNUSED       = 0057,

    SYS_LAST_KEY        = 0104, /* Код последней введённой клавиши */
    SYS_LAST_KEY_FLAG   = 0105, /* Признак записи кода */
    SYS_KEY_REPEAT_RATE = 0106, /* Скорость автоповтора */

    SYS_PAR_INTERF_SHADOW = 0256,
    SYS_EMT_36_PARAMS     = 0320  /* Блок параметров драйвера магнитофона */
};

/* ----- Периферийные регистры ------------------------------------------ */
enum BK_REGISTERS {
    REG_IRPS       = 0176560, /* ИРПС */
    REG_KEY_STATE  = 0177660, /* Регистр состояния клавиатуры */
    REG_KEY_DATA   = 0177662, /* Регистр данных клавиатуры */
    REG_V_SCROLL   = 0177664, /* Регистр вертикального смещения */
    REG_TVE_LIMIT  = 0177706, /* Перезагрузка/захват таймера */
    REG_TVE_COUNT  = 0177710, /* Счётчик таймера (только чтение) */
    REG_TVE_CSR    = 0177712, /* Управление таймера */
    REG_PAR_INTERF = 0177714, /* Параллельный интерфейс / джойстик */
    REG_EXT_DEV    = 0177716  /* Управление системными внешними устр-ми */
};

/* ----- Биты регистра состояния клавиатуры ----------------------------- */
enum BK_KEY_STATE_BITS {
    KEY_STATE_INT_MASK = 6, /* Маска прерываний */
    KEY_STATE_STATE    = 7  /* Флаг состояния (есть готовый байт) */
};

/* ----- Биты регистра REG_EXT_DEV -------------------------------------- */
enum BK_EXT_DEV_BITS {
    EXT_DEV_LINE        = 4,
    EXT_DEV_LINE_RDY    = 5,
    EXT_DEV_MAG_KEY     = 6, /* Бит пьезодинамика (КЛАД-2 будет шевелить им) */
    EXT_DEV_MOTOR_RDY   = 7,
    EXT_DEV_RESET_VECT  = 8
};

/* ----- Биты регистра REG_PAR_INTERF (порт джойстика «Электроника») ---- */
/* Регистр активно-низкий: 1 — клавиша/кнопка отпущена, 0 — нажата. */
enum BK_PAR_INTERF_BITS {
    PAR_INTERF_UP           = 0,
    PAR_INTERF_RIGHT        = 1,
    PAR_INTERF_DOWN         = 2,
    PAR_INTERF_LEFT         = 3,
    PAR_INTERF_A            = 4,
    PAR_INTERF_LEFT_BUTTON  = 5,
    PAR_INTERF_RIGHT_BUTTON = 6,
    PAR_INTERF_B            = 7
};

/* ----- Биты регистра управления таймера ------------------------------- */
enum BK_TVE_CSR_BITS {
    TVE_CSR_SP  = 0,
    TVE_CSR_CAP = 1,
    TVE_CSR_MON = 2,
    TVE_CSR_OS  = 3,
    TVE_CSR_RUN = 4, /* 1 — разрешить работу счётчика */
    TVE_CSR_D16 = 5, /* Делитель частоты на 16 */
    TVE_CSR_D4  = 6, /* Делитель частоты на 4 */
    TVE_CSR_FL  = 7  /* Флаг события таймера */
};

#define BK_TMR_FREQ 23438 /* Гц, clk = f/128 при f=3 МГц */

/* ----- Биты регистра REG_V_SCROLL ------------------------------------- */
enum BK_V_SCROLL_BITS {
    V_SCROLL_EXT_MEMORY = 9 /* Включить расширенную видеоОЗУ */
};

/* ----- Константы экрана БК-0010 --------------------------------------- */
enum BK_SCREEN {
    SCREEN_WORD_WIDTH      = 32,
    SCREEN_BYTE_WIDTH      = 64,
    SCREEN_PIX_HEIGHT      = 256,

    SCREEN_CLR_PX_PER_BYTE = 4,
    SCREEN_CLR_PX_PER_WORD = 8,
    SCREEN_CLR_PIX_WIDTH   = 256,

    SCREEN_BW_PX_PER_BYTE  = 8,
    SCREEN_BW_PX_PER_WORD  = 16,
    SCREEN_BW_PIX_WIDTH    = 512
};

/* ====================================================================== *
 * Адресное пространство БК и доступ к нему
 * ====================================================================== */

extern uint8_t bk_mem[BK_MEM_SIZE];

/* Сброс всей памяти и регистров к начальному состоянию. */
void bk_reset(void);

/*
 * Тик таймера БК.
 *
 * Реальный таймер БК-0010 тактируется CLK = f_CPU/128 (≈ 23,4 кГц при
 * f = 3 МГц), и может ещё делиться /4 и /16. Когда бит TVE_CSR_RUN
 * установлен, регистр REG_TVE_COUNT уменьшается на каждом такте, и
 * по достижении нуля либо перезагружается из REG_TVE_LIMIT (CAP=0,
 * непрерывный счёт), либо останавливается (OS=1, однократный).
 *
 * Эта функция получает «сколько инструкций PDP-11 успело пройти»
 * и пропорционально декрементирует таймер. Грубое приближение:
 * один такт таймера ≈ 25 инструкций (3 МГц / 128 / 5 цикл-на-инстр).
 */
void bk_tick_timer(unsigned cpu_steps);

/* Загрузка БК .BIN-файла по указанному пути.
 * Возвращает 0 при успехе; в `*out_load_addr` пишется адрес загрузки из
 * заголовка (он же — типичный entry point). */
int bk_load_bin(const char *path, uint16_t *out_load_addr);

/* Загрузить шрифт БК из бинарного образа Monitor-ПЗУ
 * (bk10_017_mon.rom, 8 КиБ). Шрифт лежит в ROM-смещении 0x141E, 10 байт
 * на глиф (row-major, LSB-first); используется EMT 016/020.
 *
 * По-умолчанию используется ВСТРОЕННЫЙ массив `klad2_font_data` (см.
 * src/klad2_font.c) — внешний файл не нужен. Эта функция перекрывает
 * встроенный шрифт ROM-вариантом из path; полезно для подмены
 * альтернативного шрифта. Возвращает 0 при успехе. */
int bk_load_rom_font(const char *path);

/* Загрузить полный образ Monitor-ПЗУ (8 КиБ) в bk_mem[MEM_ROM_MON..].
 * После этого КЛАД-2 может вызывать ROM-процедуры по адресам 0o100000
 * напрямую через JSR — в частности, ROM-функции звукового сигнала
 * («плюканье клавиш»), которые сами пишут в REG_EXT_DEV и через наш
 * write-strobe-генератор дают звук. EMT-инструкции по-прежнему пере-
 * хватываются нашим pdp11.c → emt.c, не доходят до ROM-диспетчера.
 *
 * По-умолчанию `bk_reset()` сам кладёт ВСТРОЕННЫЙ образ (см.
 * src/klad2_mon_rom.c). Эта функция перекрывает его ROM-вариантом
 * из path; полезно для подмены альтернативного ROM. */
int bk_load_rom_image(const char *path);

/* Получить указатель на 10-байтовый глиф для кода 0..255 БК.
 * Возвращает NULL, если код не печатный (управляющий) или шрифт
 * не загружен. */
const uint8_t *bk_font_glyph(uint8_t code);

/*
 * Чтение/запись байта/слова с перехватом доступа к 0o177600..0o177777.
 * Слова на PDP-11 — little-endian, нечётное выравнивание словного доступа
 * на реальной машине вызывает trap; здесь молча округлим вниз — настоящий
 * контроль выравнивания будет в интерпретаторе (Фаза 2).
 */
uint8_t  bk_read_b(uint16_t addr);
uint16_t bk_read_w(uint16_t addr);
void     bk_write_b(uint16_t addr, uint8_t value);
void     bk_write_w(uint16_t addr, uint16_t value);

/* ----- Хук на запись (для A/B-диагностики декомпиляции) ----------------
 * Если задан, вызывается из bk_write_b/bk_write_w на каждую запись.
 *   `is_word` = 1 для word-записи, 0 для байтовой.
 *   `value` — записываемое значение (uint16_t — для байтовой используется
 *   только младшие 8 бит).
 * По умолчанию указатель NULL → нулевые накладные расходы. */
typedef void (*bk_write_hook_fn)(uint16_t addr, uint16_t value, int is_word);
extern bk_write_hook_fn bk_write_hook;

#endif /* KLAD2_BK_H */
