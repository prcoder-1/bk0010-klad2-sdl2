/*
 * Звуковой бэкенд: получает «уровень динамика» (0/1) от записи в бит
 * EXT_DEV_MAG_KEY регистра REG_EXT_DEV и должен переводить это в PCM-
 * вывод через SDL2.
 *
 * В Фазе 1 — пустая заглушка, чтобы запись в регистр не падала. Реальный
 * генератор меандра/очередь запросов появятся в Фазе 8.
 */

#ifndef KLAD2_AUDIO_H
#define KLAD2_AUDIO_H

int  audio_init(void);
void audio_shutdown(void);

/* level: 0 — динамик «отпущен», 1 — «нажат». В реальной БК меняется
 * с частотой выходного тона. */
void audio_speaker_set(int level);

/* Вызывается интерпретатором после каждой PDP-11-инструкции —
 * накапливает дробное число «выходных сэмплов на инструкцию» и
 * эмитит сэмпл в кадровый буфер при достижении 1.0. */
void audio_step(void);

/* Вызывается из главного цикла после каждого пакета инструкций
 * (один кадр), сбрасывает накопленные сэмплы в SDL-очередь воспро-
 * изведения. */
void audio_flush(void);

/* Эмитировать короткий звуковой сигнал «пиньк» — это эмуляция ROM-
 * процедуры BEL для EMT 016 с R0=7, которую КЛАД-2 использует для
 * звука выстрела и пробивания стен. Прямой square-wave вброс в
 * SDL-очередь. */
void audio_emit_bell(void);

/* Эмулятор «бульканья» при анимации гибели героя в воде.
 * Вызывается из C-замены R_0bd4_death_tick на каждой итерации main
 * loop'а пока активна death animation. Продлевает «drown mode» на
 * ~50 мс; пока он активен, audio_flush синтезирует непрерывный
 * меандр со свипом 800→200 Гц по РЕАЛЬНОМУ времени (независимо от
 * темпа CPU). Это даёт правильное звучание «буль-буль-буль»
 * независимо от того, насколько медленно или быстро КЛАД-2 крутит
 * animation loop в нашем интерпретаторе. */
void audio_emit_drown_tick(void);

#endif /* KLAD2_AUDIO_H */
